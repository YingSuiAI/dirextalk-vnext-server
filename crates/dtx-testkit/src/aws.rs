#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ExecutorResourceState {
    Active,
    Destroyed,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ExecutorObservation {
    resource_id: JobResourceId,
    worker_id: WorkerId,
    spec_hash: CloudDigest,
    tags: ExecutorTags,
    state: ExecutorResourceState,
}

impl ExecutorObservation {
    #[must_use]
    pub const fn resource_id(&self) -> JobResourceId {
        self.resource_id
    }
    #[must_use]
    pub const fn worker_id(&self) -> WorkerId {
        self.worker_id
    }
    #[must_use]
    pub const fn spec_hash(&self) -> CloudDigest {
        self.spec_hash
    }
    #[must_use]
    pub const fn tags(&self) -> &ExecutorTags {
        &self.tags
    }
    #[must_use]
    pub const fn state(&self) -> ExecutorResourceState {
        self.state
    }

    fn matches(&self, request: &EnsureExecutorRequest) -> bool {
        self.resource_id == request.resource_id
            && self.worker_id == request.worker_id
            && self.spec_hash == request.spec_hash
            && self.tags.tenant_id == request.tenant_id
            && self.tags.job_id == request.job_id
            && self.tags.plan_hash == request.plan_hash
            && self.tags.lifecycle == ResourceLifecycle::Ephemeral
            && self.tags.expires_at_millis == request.expires_at_millis
            && self.state == ExecutorResourceState::Active
    }
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
