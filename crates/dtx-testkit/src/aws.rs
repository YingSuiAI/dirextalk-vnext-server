pub type CloudDigest = [u8; 32];

/// Closed, typed request for the first fake AWS mutation capability.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct EnsureExecutorRequest {
    operation_id: RequestId,
    tenant_id: TenantId,
    job_id: JobId,
    resource_id: JobResourceId,
    worker_id: WorkerId,
    lease_epoch: u64,
    spec_hash: CloudDigest,
    plan_hash: CloudDigest,
    expires_at_millis: i64,
}

impl EnsureExecutorRequest {
    #[allow(clippy::too_many_arguments)]
    pub fn new(
        operation_id: RequestId,
        tenant_id: TenantId,
        job_id: JobId,
        resource_id: JobResourceId,
        worker_id: WorkerId,
        lease_epoch: u64,
        spec_hash: CloudDigest,
        plan_hash: CloudDigest,
        expires_at_millis: i64,
    ) -> Result<Self, FakeAwsError> {
        validate_epoch(lease_epoch)?;
        if expires_at_millis <= 0 {
            return Err(FakeAwsError::InvalidExpiry);
        }
        Ok(Self {
            operation_id,
            tenant_id,
            job_id,
            resource_id,
            worker_id,
            lease_epoch,
            spec_hash,
            plan_hash,
            expires_at_millis,
        })
    }

    #[must_use]
    pub const fn operation_id(&self) -> RequestId {
        self.operation_id
    }
    #[must_use]
    pub const fn tenant_id(&self) -> TenantId {
        self.tenant_id
    }
    #[must_use]
    pub const fn job_id(&self) -> JobId {
        self.job_id
    }
    #[must_use]
    pub const fn resource_id(&self) -> JobResourceId {
        self.resource_id
    }
    #[must_use]
    pub const fn worker_id(&self) -> WorkerId {
        self.worker_id
    }
    #[must_use]
    pub const fn lease_epoch(&self) -> u64 {
        self.lease_epoch
    }
    #[must_use]
    pub const fn spec_hash(&self) -> CloudDigest {
        self.spec_hash
    }
    #[must_use]
    pub const fn plan_hash(&self) -> CloudDigest {
        self.plan_hash
    }
    #[must_use]
    pub const fn expires_at_millis(&self) -> i64 {
        self.expires_at_millis
    }
}

