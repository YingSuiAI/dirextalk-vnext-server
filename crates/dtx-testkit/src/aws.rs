/// Typed ephemeral-group destruction request.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct DestroyEphemeralGroupRequest {
    operation_id: RequestId,
    tenant_id: TenantId,
    job_id: JobId,
    lease_epoch: u64,
    plan_hash: CloudDigest,
}

impl DestroyEphemeralGroupRequest {
    pub fn new(
        operation_id: RequestId,
        tenant_id: TenantId,
        job_id: JobId,
        lease_epoch: u64,
        plan_hash: CloudDigest,
    ) -> Result<Self, FakeAwsError> {
        validate_epoch(lease_epoch)?;
        Ok(Self {
            operation_id,
            tenant_id,
            job_id,
            lease_epoch,
            plan_hash,
        })
    }
}

fn validate_epoch(epoch: u64) -> Result<(), FakeAwsError> {
    if epoch == 0 {
        Err(FakeAwsError::InvalidLeaseEpoch)
    } else {
        Ok(())
    }
}

